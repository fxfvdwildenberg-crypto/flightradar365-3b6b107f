export const waypointByName = (name: string): Waypoint | undefined =>
  WAYPOINTS.find((w) => w.name === name.trim().toUpperCase());

/** Waypoints closest to a world position, handy for map-side pickers. */
export function nearestWaypoints(x: number, y: number, count = 8): Waypoint[] {
  return [...WAYPOINTS]
    .sort((a, b) => Math.hypot(a.x - x, a.y - y) - Math.hypot(b.x - x, b.y - y))
    .slice(0, count);
}
